import { test, expect } from '@playwright/test';
import { randomBytes } from 'node:crypto';
import sharp from 'sharp';

test('cadastro → login → publicação → visitante → logout e segurança', async ({ page, request, baseURL }, testInfo) => {
  const suffix = `${Date.now()}-${testInfo.project.name}`;
  const email = `verificacao-${suffix}@example.invalid`;
  const senha = randomBytes(24).toString('hex');
  const origin = new URL(baseURL).origin;
  const headers = { origin };
  const post = (url, data, extra = {}) => request.post(url, { headers, data, ...extra });
  console.log('Etapa: leitura pública e validações');
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Avisos da comunidade' })).toBeVisible();
  expect((await request.get('/api/saude')).status()).toBe(200);
  expect((await post('/api/cadastro', { nome: 'X', email: 'invalido', senha: '1' })).status()).toBe(400);
  expect((await request.post('/api/sair', { headers: { origin: 'https://origem-invalida.example' } })).status()).toBe(403);
  expect((await request.post('/api/sair')).status()).toBe(403);
  expect((await post('/api/avisos', {})).status()).toBe(401);
  for (const route of ['/publicar', '/meus-avisos']) {
    const response = await request.get(route, { maxRedirects: 0 });
    expect(response.status()).toBe(307); expect(response.headers().location).toBe('/entrar');
  }
  console.log('Etapa: cadastro');
  await page.goto('/cadastrar');
  await page.getByLabel('Seu nome completo').fill('Verificação automatizada');
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill(senha);
  await page.getByRole('button', { name: 'Criar minha conta' }).click();
  await expect(page).toHaveURL(/entrar\?cadastro=ok/);
  expect((await post('/api/cadastro', { nome: 'Verificação automatizada', email: email.toUpperCase(), senha })).status()).toBe(409);
  expect((await post('/api/entrar', { email, senha: 'incorreta-123' })).status()).toBe(401);
  console.log('Etapa: login');
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill(senha);
  await page.getByRole('button', { name: 'Entrar na minha conta' }).click();
  await expect(page.getByRole('button', { name: 'Sair', exact: true })).toBeVisible();
  const cookie = (await page.context().cookies()).find(c => c.name === 'pva_session');
  expect(cookie.httpOnly).toBe(true); expect(cookie.secure).toBe(true); expect(cookie.sameSite).toBe('Lax');
  const authApi = page.context().request;
  const fields = { titulo: `[TESTE AUTOMATIZADO] Texto ${suffix}`, descricao: 'Publicação de verificação técnica, sem relato de ocorrência real. <script>window.xss=1</script>', categoria: 'Outros', bairro: 'Centro' };
  const upload = (buffer, mimeType, name) => authApi.post('/api/avisos', { headers, multipart: { ...fields, imagem: { name, mimeType, buffer } } });
  expect((await upload(Buffer.from('arquivo inválido'), 'application/pdf', 'teste.pdf')).status()).toBe(400);
  const png = await sharp({ create: { width: 80, height: 60, channels: 3, background: '#173e79' } }).png().toBuffer();
  expect((await upload(png, 'image/png', 'foto.exe')).status()).toBe(400);
  expect((await upload(Buffer.from([137,80,78,71,13,10,26,10,0,0,0,0]), 'image/png', 'falsa.png')).status()).toBe(400);
  expect((await upload(Buffer.alloc(2 * 1024 * 1024 + 1), 'image/png', 'grande.png')).status()).toBe(400);
  expect((await authApi.post('/api/avisos', { headers, multipart: { ...fields, categoria: 'Inexistente' } })).status()).toBe(400);
  console.log('Etapa: publicação');
  const noPhoto = await authApi.post('/api/avisos', { headers, multipart: fields });
  expect(noPhoto.status()).toBe(201);
  const textId = (await noPhoto.json()).id;
  await page.goto(`/avisos/${textId}`);
  await expect(page.getByRole('heading', { name: fields.titulo, exact: true })).toBeVisible();
  expect(await page.evaluate(() => window.xss)).toBeUndefined();
  await page.goto('/publicar');
  const title = `[TESTE AUTOMATIZADO] Foto ${suffix}`;
  await page.getByLabel('Título do aviso').fill(title);
  await page.getByLabel('Descrição', { exact: true }).fill('Imagem de verificação técnica. Esta publicação não relata uma ocorrência real.');
  await page.getByLabel('Categoria').selectOption('Outros');
  await page.getByLabel('Bairro').fill('Centro');
  await page.locator('input[type=file]').setInputFiles({ name: 'verificacao.png', mimeType: 'image/png', buffer: png });
  await page.getByRole('button', { name: 'Publicar aviso', exact: true }).click();
  await expect(page).toHaveURL(/\/avisos\/\d+$/);
  const photoId = new URL(page.url()).pathname.split('/').pop();
  await expect(page.locator('.detail-image img')).toBeVisible();
  expect(await page.locator('.detail-image img').evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true);
  await page.goto('/meus-avisos');
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await page.goto('/?categoria=Outros&bairro=Centro');
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await page.goto('/?categoria=Feiras&bairro=Centro');
  await expect(page.getByRole('heading', { name: title, exact: true })).toHaveCount(0);
  await page.goto('/?categoria=Outros&bairro=Centro');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: `test-results/${testInfo.project.name}-feed.png`, fullPage: true });
  const photo = await request.get(`/api/avisos/${photoId}/imagem`);
  expect(photo.status()).toBe(200); expect(photo.headers()['content-type']).toBe('image/png');
  expect((await photo.body()).length).toBeGreaterThan(50);
  expect((await request.get(`/avisos/${textId}`)).status()).toBe(200);
  const before = `pva_session=${cookie.value}`;
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Entrar', exact: true })).toBeVisible();
  expect((await authApi.post('/api/avisos', { headers, multipart: fields })).status()).toBe(401);
  expect((await request.post('/api/avisos', { headers: { ...headers, cookie: before }, multipart: fields })).status()).toBe(401);
  // Limite de login persiste inclusive sob chamadas concorrentes.
  const bruteEmail = `limite-${suffix}@example.invalid`;
  const attempts = await Promise.all(Array.from({ length: 10 }, () => post('/api/entrar', { email: bruteEmail, senha: 'invalida-123' })));
  expect(attempts.filter(r => r.status() === 401).length).toBe(8);
  expect(attempts.filter(r => r.status() === 429).length).toBe(2);
});
